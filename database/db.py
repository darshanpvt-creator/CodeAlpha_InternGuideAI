
import os
import sqlite3
from pathlib import Path
from contextlib import contextmanager

import psycopg
from psycopg.rows import dict_row


DATABASE_URL = os.environ.get("DATABASE_URL")

DB_PATH = Path(
    os.environ.get(
        "DATABASE_PATH",
        str(Path(__file__).resolve().parent / "internguide.db")
    )
).expanduser()

if not DATABASE_URL:
    DB_PATH.parent.mkdir(parents=True, exist_ok=True)


@contextmanager
def get_connection():
    if DATABASE_URL:
        connection = psycopg.connect(
            DATABASE_URL,
            row_factory=dict_row
        )
    else:
        connection = sqlite3.connect(DB_PATH)
        connection.row_factory = sqlite3.Row

    try:
        yield connection
        connection.commit()
    except Exception:
        connection.rollback()
        raise
    finally:
        connection.close()


def execute(connection, query, params=()):
    if DATABASE_URL:
        query = query.replace("?", "%s")

    return connection.execute(query, params)


def init_db():
    with get_connection() as connection:
        if DATABASE_URL:
            id_type = "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
            timestamp_type = "TIMESTAMP DEFAULT CURRENT_TIMESTAMP"
            foreign_id_type = "BIGINT"
        else:
            id_type = "INTEGER PRIMARY KEY AUTOINCREMENT"
            timestamp_type = "TIMESTAMP DEFAULT CURRENT_TIMESTAMP"
            foreign_id_type = "INTEGER"

        execute(connection, f"""
            CREATE TABLE IF NOT EXISTS conversations (
                id TEXT PRIMARY KEY,
                created_at {timestamp_type}
            )
        """)

        execute(connection, f"""
            CREATE TABLE IF NOT EXISTS messages (
                id {id_type},
                conversation_id TEXT NOT NULL,
                role TEXT NOT NULL CHECK(role IN ('user', 'assistant')),
                content TEXT NOT NULL,
                created_at {timestamp_type},
                FOREIGN KEY (conversation_id) REFERENCES conversations(id)
            )
        """)

        execute(connection, f"""
            CREATE TABLE IF NOT EXISTS feedback (
                id {id_type},
                conversation_id TEXT NOT NULL,
                message_id {foreign_id_type},
                rating TEXT NOT NULL CHECK(rating IN ('helpful', 'not_helpful')),
                created_at {timestamp_type},
                FOREIGN KEY (conversation_id) REFERENCES conversations(id),
                FOREIGN KEY (message_id) REFERENCES messages(id)
            )
        """)

        execute(connection, f"""
            CREATE TABLE IF NOT EXISTS unanswered_questions (
                id {id_type},
                conversation_id TEXT NOT NULL,
                question TEXT NOT NULL,
                confidence REAL NOT NULL,
                created_at {timestamp_type},
                FOREIGN KEY (conversation_id) REFERENCES conversations(id)
            )
        """)


def save_message(conversation_id, role, content):
    if not conversation_id or role not in ("user", "assistant"):
        raise ValueError("Invalid conversation ID or message role.")

    if not isinstance(content, str) or not content.strip():
        raise ValueError("Message content cannot be empty.")

    with get_connection() as connection:
        execute(
            connection,
            """
            INSERT INTO conversations (id)
            VALUES (?)
            ON CONFLICT (id) DO NOTHING
            """,
            (conversation_id,)
        )

        if DATABASE_URL:
            cursor = execute(
                connection,
                """
                INSERT INTO messages (conversation_id, role, content)
                VALUES (?, ?, ?)
                RETURNING id
                """,
                (conversation_id, role, content.strip())
            )
            return cursor.fetchone()["id"]

        cursor = execute(
            connection,
            """
            INSERT INTO messages (conversation_id, role, content)
            VALUES (?, ?, ?)
            """,
            (conversation_id, role, content.strip())
        )

        return cursor.lastrowid


def get_messages(conversation_id):
    with get_connection() as connection:
        rows = execute(
            connection,
            """
            SELECT id, role, content, created_at
            FROM messages
            WHERE conversation_id = ?
            ORDER BY id ASC
            """,
            (conversation_id,)
        ).fetchall()

    return [dict(row) for row in rows]


def save_feedback(conversation_id, message_id, rating):
    if not conversation_id:
        raise ValueError("Conversation ID is required.")

    if rating not in ("helpful", "not_helpful"):
        raise ValueError("Invalid feedback rating.")

    with get_connection() as connection:
        execute(
            connection,
            """
            INSERT INTO feedback (conversation_id, message_id, rating)
            VALUES (?, ?, ?)
            """,
            (conversation_id, message_id, rating)
        )


def save_unanswered_question(conversation_id, question, confidence):
    if not conversation_id:
        raise ValueError("Conversation ID is required.")

    if not isinstance(question, str) or not question.strip():
        raise ValueError("Question cannot be empty.")

    with get_connection() as connection:
        execute(
            connection,
            """
            INSERT INTO conversations (id)
            VALUES (?)
            ON CONFLICT (id) DO NOTHING
            """,
            (conversation_id,)
        )

        execute(
            connection,
            """
            INSERT INTO unanswered_questions
            (conversation_id, question, confidence)
            VALUES (?, ?, ?)
            """,
            (conversation_id, question.strip(), confidence)
        )


if __name__ == "__main__":
    init_db()
    print("InternGuide AI database initialized successfully!")
